// PRIVACY.md and TERMS.md are the source of truth (this repo is private). This script writes:
//   src/legalDocs.ts — the same text bundled into the app, shown offline (never a 404)
//   site/            — the public website (GitHub Pages repo aronipani/takesure): privacy, terms, support
// Run after changing either file:  npm run legal-docs
// Then copy site/* into the takesure repo and push (see site/README.md). A test fails if the app copy is stale.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const privacy = readFileSync('PRIVACY.md', 'utf8');
const terms = readFileSync('TERMS.md', 'utf8');

writeFileSync(
  'src/legalDocs.ts',
  `// Generated by scripts/legal-docs.mjs from PRIVACY.md and TERMS.md — do not edit by hand.\n` +
    `export const PRIVACY_TEXT = ${JSON.stringify(privacy)};\n` +
    `export const TERMS_TEXT = ${JSON.stringify(terms)};\n`,
);

const page = (title, permalink, body) => `---\ntitle: ${title}\npermalink: ${permalink}\n---\n\n${body.trim()}\n`;
mkdirSync('site', { recursive: true });
writeFileSync('site/privacy.md', page('TakeSure privacy policy', '/privacy/', privacy));
writeFileSync('site/terms.md', page('TakeSure terms of use', '/terms/', terms));
writeFileSync(
  'site/index.md',
  page(
    'TakeSure',
    '/',
    `# TakeSure

A free medicine reminder for families — made for Indian medicine strips, for parents and grandparents who take many
medicines a day, and for the family members who look after them, wherever they live.

No account, no ads, no tracking. Everything stays on your phone.

* [Privacy policy](privacy/)
* [Terms of use](terms/)

## Support
* In the app: **Settings → Help → Report a problem** (opens an email you send yourself).
* Email: [paniaron@gmail.com](mailto:paniaron@gmail.com)

TakeSure is a reminder and record-keeping aid. It is not a medical device and does not diagnose, treat or decide
doses. In an emergency call your doctor or emergency services (112 in India, 911 in the US).`,
  ),
);
writeFileSync('site/_config.yml', 'title: TakeSure\ndescription: Free family medicine reminders\ntheme: jekyll-theme-primer\n');
writeFileSync(
  'site/README.md',
  `# TakeSure — public pages

Privacy policy, terms of use and support for the TakeSure app, served by GitHub Pages at
https://aronipani.github.io/takesure/ . Generated from the app's source; don't edit here.
`,
);
console.log('Wrote src/legalDocs.ts and site/ (index, privacy, terms).');
