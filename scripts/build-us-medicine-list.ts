// Builds src/data/us-medicines.ts from the FDA NDC Directory (public domain, CC0). See docs/specs/18-us-medicine-list.md.
//   node --experimental-strip-types scripts/build-us-medicine-list.ts            (downloads the FDA file)
//   node --experimental-strip-types scripts/build-us-medicine-list.ts --zip ndctext.zip
// Run monthly by .github/workflows/us-medicine-list.yml. Stops without writing anything when the result looks wrong.
import { readFileSync, writeFileSync } from 'node:fs';
import { inflateRawSync } from 'node:zlib';
import { buildUsList, lookupUs, type UsList } from '../src/uslist.ts';

const FDA_URL = 'https://www.accessdata.fda.gov/cder/ndctext.zip';
const MAX_BYTES = 12_000_000; // the app should not grow by more than this
const MIN_PACKAGES = 20_000; // far fewer means the download or the format went wrong

const args = new Map<string, string>();
for (let i = 2; i < process.argv.length; i += 2) args.set(process.argv[i].replace(/^--/, ''), process.argv[i + 1] ?? '');
const out = args.get('out') ?? new URL('../src/data/us-medicines.ts', import.meta.url).pathname;

/** The files inside a .zip (stored or deflated), read from its central directory. */
function unzip(buf: Buffer): Map<string, Buffer> {
  let eocd = buf.length - 22;
  while (eocd >= 0 && buf.readUInt32LE(eocd) !== 0x06054b50) eocd--;
  if (eocd < 0) throw new Error('Not a zip file');
  const count = buf.readUInt16LE(eocd + 10);
  let p = buf.readUInt32LE(eocd + 16);
  const files = new Map<string, Buffer>();
  for (let i = 0; i < count; i++) {
    if (buf.readUInt32LE(p) !== 0x02014b50) throw new Error('Bad zip directory');
    const method = buf.readUInt16LE(p + 10);
    const size = buf.readUInt32LE(p + 20);
    const nameLen = buf.readUInt16LE(p + 28);
    const extraLen = buf.readUInt16LE(p + 30);
    const commentLen = buf.readUInt16LE(p + 32);
    const local = buf.readUInt32LE(p + 42);
    const name = buf.toString('utf8', p + 46, p + 46 + nameLen);
    const start = local + 30 + buf.readUInt16LE(local + 26) + buf.readUInt16LE(local + 28);
    const data = buf.subarray(start, start + size);
    files.set(name.split('/').pop()!.toLowerCase(), method === 8 ? inflateRawSync(data) : data);
    p += 46 + nameLen + extraLen + commentLen;
  }
  return files;
}

async function main() {
  const zipPath = args.get('zip');
  let zip: Buffer;
  if (zipPath) zip = readFileSync(zipPath);
  else {
    console.log(`downloading ${FDA_URL}`);
    const res = await fetch(FDA_URL, { headers: { 'User-Agent': 'TakeSure medicine list build (github.com/aronipani/medsync)' } });
    if (!res.ok) throw new Error(`FDA download failed: HTTP ${res.status}`);
    zip = Buffer.from(await res.arrayBuffer());
  }
  const files = unzip(zip);
  const product = files.get('product.txt');
  const pkg = files.get('package.txt');
  if (!product || !pkg) throw new Error(`product.txt / package.txt not in the zip (found: ${[...files.keys()].join(', ')})`);
  const built = new Date().toISOString().slice(0, 10);
  // The FDA files are Windows-1252; latin1 keeps every byte as one character.
  const { list, stats } = buildUsList(product.toString('latin1'), pkg.toString('latin1'), 'FDA NDC Directory (public domain, CC0)', built);
  console.log(JSON.stringify(stats, null, 1));
  check(list);
  const body = JSON.stringify(list);
  writeFileSync(
    out,
    `// GENERATED by scripts/build-us-medicine-list.ts — do not edit by hand. See docs/specs/18-us-medicine-list.md.\n` +
      `import type { UsList } from '../uslist.ts';\n\n` +
      `export const US_MEDICINES: UsList = ${body};\n`,
  );
  console.log(`wrote ${out} (${(body.length / 1e6).toFixed(2)} MB, ${list.products.length} products, ${list.ndc.length / 14} package codes)`);
}

/** Refuse a list that is clearly wrong rather than shipping it. */
function check(list: UsList) {
  const packages = list.ndc.length / 14;
  const size = JSON.stringify(list).length;
  const problems: string[] = [];
  if (packages < MIN_PACKAGES) problems.push(`only ${packages} package codes (expected over ${MIN_PACKAGES})`);
  if (size > MAX_BYTES) problems.push(`list is ${(size / 1e6).toFixed(1)} MB (limit ${MAX_BYTES / 1e6} MB)`);
  if (!list.products.some((p) => /^albuterol$/i.test(p[1]) && p[3] === 'puff')) problems.push('no albuterol inhaler found');
  // Spot check: the first package code must look up again.
  const first = list.ndc.slice(0, 10);
  if (!lookupUs(list, `NDC ${first.slice(0, 4)}-${first.slice(4, 8)}-${first.slice(8)}`)) problems.push('lookup check failed');
  if (problems.length) throw new Error(`Not writing the US list: ${problems.join('; ')}`);
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
