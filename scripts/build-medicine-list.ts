// Builds src/data/medicines.ts from a CSV of medicines. See docs/specs/04-offline-medicine-list.md.
//   node --experimental-strip-types scripts/build-medicine-list.ts --csv data.csv --name name \
//     --composition short_composition1,short_composition2 --skip-if Is_discontinued=TRUE --source "Dataset, licence"
import { readFileSync, writeFileSync } from 'node:fs';
import { DRUGS } from '../src/drugdb.ts';
import { compile, parseCsv } from '../src/medlist.ts';

const args = new Map<string, string>();
for (let i = 2; i < process.argv.length; i += 2) args.set(process.argv[i].replace(/^--/, ''), process.argv[i + 1] ?? '');
const csv = args.get('csv');
const source = args.get('source');
if (!csv || !source) {
  console.error('Usage: --csv FILE --source "where it came from, licence" [--name COL] [--composition COL1,COL2] [--skip-if COL=VALUE]');
  process.exit(1);
}
const nameCol = args.get('name') ?? 'name';
const compCols = (args.get('composition') ?? 'composition').split(',');
const [skipCol, skipVal] = (args.get('skip-if') ?? '').split('=');

const rows = parseCsv(readFileSync(csv, 'utf8')).map((r) => ({
  name: r[nameCol] ?? '',
  composition: compCols.map((c) => r[c] ?? '').filter(Boolean).join(' + '),
  skip: !!skipCol && (r[skipCol] ?? '').toLowerCase() === (skipVal ?? '').toLowerCase(),
}));
const handChecked = new Set(DRUGS.flatMap((d) => d.brands).map((b) => b.toLowerCase().replace(/[^a-z0-9]/g, '')));
const { list, stats } = compile(rows, handChecked, source, new Date().toISOString().slice(0, 10));
const out = args.get('out') ?? new URL('../src/data/medicines.ts', import.meta.url).pathname;
writeFileSync(
  out,
  `// GENERATED by scripts/build-medicine-list.ts — do not edit by hand. See docs/specs/04-offline-medicine-list.md.\n` +
    `import type { CompactList } from '../medlist.ts';\n\n` +
    `export const MEDICINES: CompactList = ${JSON.stringify(list)};\n`,
);
console.log(JSON.stringify(stats, null, 1));
console.log(`wrote ${out} (${(JSON.stringify(list).length / 1e6).toFixed(2)} MB)`);
